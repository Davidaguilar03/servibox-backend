-- Gobierno de tenants desde la plataforma (tarea 5A). activo_tenant sigue siendo el estado:
-- true ACTIVE, false SUSPENDED. Las filas existentes quedan en version 0 y sin datos de
-- suspension; un tenant ya inactivo antes de V11 conserva su estado sin motivo.
ALTER TABLE tenants ADD COLUMN version_tenant BIGINT NOT NULL DEFAULT 0;
ALTER TABLE tenants ADD COLUMN fecha_suspension_tenant TIMESTAMP;
ALTER TABLE tenants ADD COLUMN motivo_suspension_tenant VARCHAR(500);
ALTER TABLE tenants ADD CONSTRAINT ck_tenant_version CHECK (version_tenant >= 0);
ALTER TABLE tenants ADD CONSTRAINT ck_tenant_suspension CHECK (
    activo_tenant = FALSE OR (fecha_suspension_tenant IS NULL AND motivo_suspension_tenant IS NULL));

-- Debe coincidir con el claim authVersion del JWT tenant; revocar la sube. Un token sin el
-- claim (emitido antes de V11) cuenta como 0.
ALTER TABLE usuarios ADD COLUMN auth_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE usuarios ADD CONSTRAINT ck_usuario_auth_version CHECK (auth_version >= 0);

-- Bitacora de acciones de escritura de la plataforma. Solo insercion. El tenant y el usuario
-- afectados van sin FK a proposito: el registro debe sobrevivir a un borrado permanente.
CREATE TABLE auditoria_plataforma (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion VARCHAR(30) NOT NULL,
    id_administrador BIGINT NOT NULL,
    id_tenant_objetivo BIGINT NOT NULL,
    id_usuario_objetivo BIGINT,
    motivo VARCHAR(500),
    fecha_auditoria TIMESTAMP NOT NULL,
    CONSTRAINT fk_auditoria_administrador FOREIGN KEY (id_administrador)
        REFERENCES administradores_plataforma (id_administrador) ON DELETE RESTRICT,
    CONSTRAINT ck_auditoria_accion CHECK (accion IN
        ('SUSPEND_TENANT', 'REACTIVATE_TENANT', 'REVOKE_USER_SESSIONS', 'REVOKE_TENANT_SESSIONS'))
);

CREATE INDEX idx_auditoria_tenant_fecha ON auditoria_plataforma (id_tenant_objetivo, fecha_auditoria);
