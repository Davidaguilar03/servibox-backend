-- Una fila por enlace emitido. Solo el SHA-256 del token; el token crudo no se guarda.
-- La generacion unica por solicitud la garantiza el bloqueo de la solicitud al emitir.
CREATE TABLE activaciones_registro (
    id_activacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud VARCHAR(36) NOT NULL,
    generacion INTEGER NOT NULL,
    digest_token VARCHAR(64) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    expira_en TIMESTAMP NOT NULL,
    fecha_consumo TIMESTAMP,
    fecha_revocacion TIMESTAMP,
    CONSTRAINT uk_activacion_digest UNIQUE (digest_token),
    CONSTRAINT fk_activacion_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitudes_registro (id_solicitud) ON DELETE RESTRICT,
    CONSTRAINT ck_activacion_generacion CHECK (generacion >= 1),
    CONSTRAINT ck_activacion_cierre CHECK (fecha_consumo IS NULL OR fecha_revocacion IS NULL)
);

CREATE INDEX idx_activacion_solicitud ON activaciones_registro (id_solicitud, generacion);

-- Outbox de correo. El cuerpo va cifrado (AES-GCM, clave runtime propia) y solo mientras
-- el mensaje esta PENDING; al enviarse, fallar, revocarse o vencer se borra.
CREATE TABLE correos_salientes (
    id_correo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activacion BIGINT NOT NULL,
    destinatario VARCHAR(150) NOT NULL,
    plantilla VARCHAR(30) NOT NULL,
    payload_cifrado VARCHAR(4000),
    estado VARCHAR(10) NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    proximo_intento TIMESTAMP NOT NULL,
    reclamado_hasta TIMESTAMP,
    expira_en TIMESTAMP NOT NULL,
    ultimo_error VARCHAR(100),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_envio TIMESTAMP,
    CONSTRAINT fk_correo_activacion FOREIGN KEY (id_activacion)
        REFERENCES activaciones_registro (id_activacion) ON DELETE RESTRICT,
    CONSTRAINT ck_correo_estado CHECK (estado IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_correo_plantilla CHECK (plantilla IN ('ACTIVATION')),
    CONSTRAINT ck_correo_intentos CHECK (intentos >= 0),
    CONSTRAINT ck_correo_payload CHECK (estado = 'PENDING' OR payload_cifrado IS NULL),
    CONSTRAINT ck_correo_envio CHECK (
        (estado = 'SENT' AND fecha_envio IS NOT NULL) OR (estado <> 'SENT' AND fecha_envio IS NULL))
);

CREATE INDEX idx_correo_pendiente ON correos_salientes (estado, proximo_intento);
CREATE INDEX idx_correo_activacion ON correos_salientes (id_activacion);
