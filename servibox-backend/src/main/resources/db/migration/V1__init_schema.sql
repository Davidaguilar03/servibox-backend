-- Esquema inicial de ServiBox, escrito a mano desde docs/ai-context/04-DATA-MODEL.md.
-- Compatible con PostgreSQL 16 y con H2 en modo PostgreSQL. Sin datos semilla.
-- Tipos: identificadores BIGINT; montos NUMERIC(14,2); tasas como fraccion NUMERIC(8,6);
-- fechas de negocio DATE; auditoria TIMESTAMP en UTC; enums VARCHAR.
-- Las FK son ON DELETE RESTRICT: nada con historial se elimina.

CREATE TABLE tenants (
    id_tenant             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_tenant         VARCHAR(150) NOT NULL,
    slug_tenant           VARCHAR(100) NOT NULL,
    activo_tenant         BOOLEAN      NOT NULL,
    fecha_creacion_tenant TIMESTAMP    NOT NULL,
    CONSTRAINT pk_tenants PRIMARY KEY (id_tenant),
    CONSTRAINT uk_tenant_slug UNIQUE (slug_tenant)
);

CREATE TABLE usuarios (
    id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant     BIGINT       NOT NULL,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email         VARCHAR(150),
    activo        BOOLEAN      NOT NULL,
    rol           VARCHAR(30)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_tenant_username UNIQUE (id_tenant, username),
    CONSTRAINT fk_usuario_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT
);

CREATE TABLE configuracion_financiera (
    id_configuracion            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant                   BIGINT        NOT NULL,
    porcentaje_gastos           NUMERIC(8, 6) NOT NULL,
    porcentaje_dian             NUMERIC(8, 6) NOT NULL,
    porcentaje_ica              NUMERIC(8, 6) NOT NULL,
    porcentaje_comision_tarjeta NUMERIC(8, 6) NOT NULL,
    created_at                  TIMESTAMP     NOT NULL,
    updated_at                  TIMESTAMP     NOT NULL,
    CONSTRAINT pk_configuracion_financiera PRIMARY KEY (id_configuracion),
    CONSTRAINT uk_configuracion_tenant UNIQUE (id_tenant),
    CONSTRAINT fk_configuracion_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT ck_configuracion_porcentaje_gastos CHECK (porcentaje_gastos BETWEEN 0 AND 1),
    CONSTRAINT ck_configuracion_porcentaje_dian CHECK (porcentaje_dian BETWEEN 0 AND 1),
    CONSTRAINT ck_configuracion_porcentaje_ica CHECK (porcentaje_ica BETWEEN 0 AND 1),
    CONSTRAINT ck_configuracion_porcentaje_comision_tarjeta CHECK (porcentaje_comision_tarjeta BETWEEN 0 AND 1)
);

CREATE TABLE cuentas (
    id_cuenta       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant       BIGINT         NOT NULL,
    nombre_cuenta   VARCHAR(100)   NOT NULL,
    balance_inicial NUMERIC(14, 2) NOT NULL,
    saldo_actual    NUMERIC(14, 2) NOT NULL,
    tipo_cuenta     VARCHAR(30)    NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    CONSTRAINT pk_cuentas PRIMARY KEY (id_cuenta),
    CONSTRAINT uk_cuenta_tenant_name UNIQUE (id_tenant, nombre_cuenta),
    CONSTRAINT fk_cuenta_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT
);

CREATE TABLE terceros (
    id_tercero          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant           BIGINT       NOT NULL,
    tipo_tercero        VARCHAR(20)  NOT NULL,
    nombre_razon_social VARCHAR(150) NOT NULL,
    tipo_documento      VARCHAR(20)  NOT NULL,
    numero_documento    VARCHAR(25)  NOT NULL,
    correo              VARCHAR(150),
    celular             VARCHAR(25),
    created_at          TIMESTAMP    NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    CONSTRAINT pk_terceros PRIMARY KEY (id_tercero),
    CONSTRAINT uk_tercero_tenant_document UNIQUE (id_tenant, numero_documento),
    CONSTRAINT fk_tercero_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT
);

CREATE TABLE categoria_productos (
    id_categoria_producto     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant                 BIGINT        NOT NULL,
    nombre_categoria_producto VARCHAR(100)  NOT NULL,
    color_categoria           VARCHAR(20)   NOT NULL,
    stock_min_amarillo        INTEGER       NOT NULL,
    stock_min_rojo            INTEGER       NOT NULL,
    margen_utilidad           NUMERIC(8, 6) NOT NULL,
    created_at                TIMESTAMP     NOT NULL,
    updated_at                TIMESTAMP     NOT NULL,
    CONSTRAINT pk_categoria_productos PRIMARY KEY (id_categoria_producto),
    CONSTRAINT fk_categoria_producto_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT
);

CREATE TABLE tipos_impuesto (
    id_impuesto          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant            BIGINT        NOT NULL,
    nombre_impuesto      VARCHAR(100)  NOT NULL,
    tasa_impuesto        NUMERIC(8, 6) NOT NULL,
    descripcion_impuesto VARCHAR(255),
    aplica_transaccion   BOOLEAN       NOT NULL,
    es_iva               BOOLEAN       NOT NULL,
    created_at           TIMESTAMP     NOT NULL,
    updated_at           TIMESTAMP     NOT NULL,
    CONSTRAINT pk_tipos_impuesto PRIMARY KEY (id_impuesto),
    CONSTRAINT fk_tipo_impuesto_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT
);

CREATE TABLE categoria_impuestos (
    id_categoria_producto BIGINT NOT NULL,
    id_impuesto           BIGINT NOT NULL,
    CONSTRAINT pk_categoria_impuestos PRIMARY KEY (id_categoria_producto, id_impuesto),
    CONSTRAINT fk_categoria_impuesto_categoria FOREIGN KEY (id_categoria_producto)
        REFERENCES categoria_productos (id_categoria_producto) ON DELETE RESTRICT,
    CONSTRAINT fk_categoria_impuesto_impuesto FOREIGN KEY (id_impuesto)
        REFERENCES tipos_impuesto (id_impuesto) ON DELETE RESTRICT
);

CREATE TABLE productos (
    id_producto           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant             BIGINT         NOT NULL,
    id_categoria_producto BIGINT         NOT NULL,
    codigo_producto       VARCHAR(50)    NOT NULL,
    descripcion_producto  VARCHAR(255)   NOT NULL,
    costo_compra          NUMERIC(14, 2) NOT NULL,
    cantidad              INTEGER        NOT NULL,
    iva_producto          NUMERIC(14, 2) NOT NULL,
    precio_sugerido       NUMERIC(14, 2) NOT NULL,
    created_at            TIMESTAMP      NOT NULL,
    updated_at            TIMESTAMP      NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (id_producto),
    CONSTRAINT uk_producto_tenant_code UNIQUE (id_tenant, codigo_producto),
    CONSTRAINT fk_producto_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria_producto)
        REFERENCES categoria_productos (id_categoria_producto) ON DELETE RESTRICT
);

CREATE TABLE compras (
    id_compra                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant                BIGINT         NOT NULL,
    id_tercero               BIGINT         NOT NULL,
    numero_factura_compra    VARCHAR(50)    NOT NULL,
    fecha_compra             DATE           NOT NULL,
    fecha_vencimiento_compra DATE,
    forma_pago_compra        VARCHAR(20)    NOT NULL,
    medio_pago_compra        VARCHAR(30),
    estado_compra            VARCHAR(20)    NOT NULL,
    subtotal_compra          NUMERIC(14, 2) NOT NULL,
    iva_total_compra         NUMERIC(14, 2) NOT NULL,
    total_compra             NUMERIC(14, 2) NOT NULL,
    created_at               TIMESTAMP      NOT NULL,
    updated_at               TIMESTAMP      NOT NULL,
    CONSTRAINT pk_compras PRIMARY KEY (id_compra),
    CONSTRAINT uk_compra_tenant_invoice_number UNIQUE (id_tenant, numero_factura_compra),
    CONSTRAINT fk_compra_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_compra_tercero FOREIGN KEY (id_tercero) REFERENCES terceros (id_tercero) ON DELETE RESTRICT
);

CREATE TABLE detalle_compras (
    id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant         BIGINT         NOT NULL,
    id_compra         BIGINT         NOT NULL,
    id_producto       BIGINT         NOT NULL,
    cantidad_compra   INTEGER        NOT NULL,
    precio_compra     NUMERIC(14, 2) NOT NULL,
    iva_linea_compra  NUMERIC(14, 2) NOT NULL,
    created_at        TIMESTAMP      NOT NULL,
    updated_at        TIMESTAMP      NOT NULL,
    CONSTRAINT pk_detalle_compras PRIMARY KEY (id_detalle_compra),
    CONSTRAINT fk_detalle_compra_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_compra_compra FOREIGN KEY (id_compra) REFERENCES compras (id_compra) ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_compra_producto FOREIGN KEY (id_producto)
        REFERENCES productos (id_producto) ON DELETE RESTRICT,
    CONSTRAINT ck_detalle_compra_cantidad CHECK (cantidad_compra > 0)
);

CREATE TABLE ventas (
    id_venta                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant               BIGINT         NOT NULL,
    id_tercero              BIGINT         NOT NULL,
    numero_factura_venta    VARCHAR(50)    NOT NULL,
    fecha_venta             DATE           NOT NULL,
    fecha_vencimiento_venta DATE,
    forma_pago_venta        VARCHAR(20)    NOT NULL,
    medio_pago_venta        VARCHAR(30),
    estado_venta            VARCHAR(20)    NOT NULL,
    subtotal_venta          NUMERIC(14, 2) NOT NULL,
    iva_por_pagar_venta     NUMERIC(14, 2) NOT NULL,
    total_venta             NUMERIC(14, 2) NOT NULL,
    created_at              TIMESTAMP      NOT NULL,
    updated_at              TIMESTAMP      NOT NULL,
    CONSTRAINT pk_ventas PRIMARY KEY (id_venta),
    CONSTRAINT uk_venta_tenant_invoice_number UNIQUE (id_tenant, numero_factura_venta),
    CONSTRAINT fk_venta_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_venta_tercero FOREIGN KEY (id_tercero) REFERENCES terceros (id_tercero) ON DELETE RESTRICT
);

CREATE TABLE detalle_ventas (
    id_detalle_venta     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant            BIGINT         NOT NULL,
    id_venta             BIGINT         NOT NULL,
    id_producto          BIGINT         NOT NULL,
    cantidad_venta       INTEGER        NOT NULL,
    precio_venta         NUMERIC(14, 2) NOT NULL,
    iva_generado_linea   NUMERIC(14, 2) NOT NULL,
    diferencia_iva_linea NUMERIC(14, 2) NOT NULL,
    created_at           TIMESTAMP      NOT NULL,
    updated_at           TIMESTAMP      NOT NULL,
    CONSTRAINT pk_detalle_ventas PRIMARY KEY (id_detalle_venta),
    CONSTRAINT fk_detalle_venta_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_venta_venta FOREIGN KEY (id_venta) REFERENCES ventas (id_venta) ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (id_producto)
        REFERENCES productos (id_producto) ON DELETE RESTRICT,
    CONSTRAINT ck_detalle_venta_cantidad CHECK (cantidad_venta > 0)
);

CREATE TABLE movimientos (
    id_movimiento             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tenant                 BIGINT         NOT NULL,
    id_cuenta                 BIGINT         NOT NULL,
    id_movimiento_relacionado BIGINT,
    id_compra                 BIGINT,
    id_venta                  BIGINT,
    tipo_movimiento           VARCHAR(20)    NOT NULL,
    categoria_movimiento      VARCHAR(50)    NOT NULL,
    monto                     NUMERIC(14, 2) NOT NULL,
    fecha_movimiento          DATE           NOT NULL,
    concepto                  VARCHAR(255)   NOT NULL,
    notas                     VARCHAR(255),
    created_at                TIMESTAMP      NOT NULL,
    updated_at                TIMESTAMP      NOT NULL,
    CONSTRAINT pk_movimientos PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_movimiento_tenant FOREIGN KEY (id_tenant) REFERENCES tenants (id_tenant) ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (id_cuenta) REFERENCES cuentas (id_cuenta) ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_relacionado FOREIGN KEY (id_movimiento_relacionado)
        REFERENCES movimientos (id_movimiento) ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_compra FOREIGN KEY (id_compra) REFERENCES compras (id_compra) ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_venta FOREIGN KEY (id_venta) REFERENCES ventas (id_venta) ON DELETE RESTRICT,
    CONSTRAINT ck_movimiento_monto CHECK (monto > 0),
    CONSTRAINT ck_movimiento_factura CHECK (
        (categoria_movimiento = 'RECAUDO_VENTA' AND id_venta IS NOT NULL AND id_compra IS NULL)
        OR (categoria_movimiento = 'PAGO_COMPRA' AND id_compra IS NOT NULL AND id_venta IS NULL)
        OR (categoria_movimiento NOT IN ('RECAUDO_VENTA', 'PAGO_COMPRA')
            AND id_venta IS NULL AND id_compra IS NULL)
    )
);
